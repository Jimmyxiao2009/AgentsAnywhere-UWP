param([string]$DeviceOrigin='http://192.168.3.159',[string]$PackagePath='')
$ErrorActionPreference='Stop'
$projectRoot=Split-Path $PSScriptRoot -Parent
if(-not $PackagePath){$PackagePath=Join-Path $projectRoot 'AgentsAnywhere.Mobile\AppPackages\AgentsAnywhere.Mobile_1.0.0.5_ARM_Test\AgentsAnywhere.Mobile_1.0.0.5_ARM.appx'}
$package=Get-Item -LiteralPath $PackagePath
$base=$DeviceOrigin.TrimEnd('/')
$direct=@{}
if((Get-Command Invoke-WebRequest).Parameters.ContainsKey('NoProxy')){$direct['NoProxy']=$true}
$null=Invoke-WebRequest @direct -Uri "$base/api/os/info" -TimeoutSec 15 -SessionVariable portalSession
$existing=(Invoke-WebRequest @direct -Uri "$base/api/app/packagemanager/packages" -WebSession $portalSession -TimeoutSec 15).Content | ConvertFrom-Json
$previous=$existing.InstalledPackages | Where-Object {$_.PackageFullName -like 'AgentsAnywhere.Mobile_*'} | Select-Object -First 1
if($previous){
 $encoded=[Uri]::EscapeDataString([Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($previous.PackageFullName)))
 $null=Invoke-WebRequest @direct -Method Delete -Uri "$base/api/taskmanager/app?package=$encoded&forcestop=yes" -WebSession $portalSession -TimeoutSec 15
}
$curlArgs=@('--noproxy','*','--silent','--show-error','--fail-with-body','--max-time','120','-X','POST',"$base/api/app/packagemanager/package?package=$([Uri]::EscapeDataString($package.Name))",'-F',"package=@$($package.FullName);type=application/octet-stream")
$deps=Join-Path $package.DirectoryName 'Dependencies\ARM'
foreach($dependency in Get-ChildItem -LiteralPath $deps -Filter '*.appx' -ErrorAction SilentlyContinue){$curlArgs+=@('-F',"dependency=@$($dependency.FullName);type=application/octet-stream")}
$headers=@{}
$csrf=$portalSession.Cookies.GetCookies([Uri]$base) | Where-Object Name -eq 'CSRF-Token' | Select-Object -First 1
if($csrf){$headers['X-CSRF-Token']=$csrf.Value;$curlArgs+=@('-H',"X-CSRF-Token: $($csrf.Value)",'-H',"Cookie: CSRF-Token=$($csrf.Value)")}
# Windows 10 Mobile's old multipart parser rejects the quoted boundary generated by -Form.
& curl.exe @curlArgs
if($LASTEXITCODE -ne 0){throw 'Package upload failed.'}
Write-Output 'Upload accepted.'
for($attempt=0;$attempt -lt 60;$attempt++){
 $state=Invoke-WebRequest @direct -Uri "$base/api/app/packagemanager/state" -Headers $headers -WebSession $portalSession -TimeoutSec 15
 if($state.StatusCode -eq 200){
  Write-Output $state.Content
  $result=$state.Content | ConvertFrom-Json
  if($result.Success -eq $false){throw "Device deployment failed: $($state.Content)"}
  break
 }
 if($attempt -eq 59){throw 'Device deployment still running after two minutes.'}
 Start-Sleep -Seconds 2
}
$installed=(Invoke-WebRequest @direct -Uri "$base/api/app/packagemanager/packages" -WebSession $portalSession -TimeoutSec 15).Content | ConvertFrom-Json
$installed.InstalledPackages | Where-Object {$_.PackageFullName -like 'AgentsAnywhere.Mobile_*'} | Select-Object Name,PackageFullName,PackageFamilyName,PackageRelativeId

